class CircuitState(str, Enum):
    """Circuit breaker states."""
    CLOSED = "closed"  # Normal operation
    OPEN = "open"      # Degraded mode active
    HALF_OPEN = "half_open"  # Testing recovery


@dataclass
class CircuitBreakerConfig:
    """Configuration for the circuit breaker."""
    # Thresholds
    recall_threshold: float = 0.7  # Below this, trigger degraded mode
    latency_threshold_ms: float = 50.0  # Above this, trigger degraded mode
    hazard_threshold: float = 0.6  # Forecast hazard score threshold
    
    # Recovery
    recovery_check_interval_s: float = 30.0  # How often to check for recovery
    consecutive_successes_for_close: int = 3  # Successes needed to close circuit
    
    # Degraded mode settings
    degraded_nprobe: int = 1  # Minimum nprobe in degraded mode
    degraded_ef_search: int = 16  # Reduced ef_search for HNSW
    
    # Normal mode settings
    optimal_nprobe: int = 10
    optimal_ef_search: int = 64


@dataclass
class CircuitBreakerState:
    """Current state of the circuit breaker."""
    state: CircuitState = CircuitState.CLOSED
    consecutive_successes: int = 0
    consecutive_failures: int = 0
    last_state_change: float = 0.0
    total_interventions: int = 0
    interventions_log: list = field(default_factory=list)


